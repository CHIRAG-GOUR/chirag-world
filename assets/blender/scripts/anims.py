"""
Animation clips for Chirag's game_engine rig.

Locomotion (idle / walk / run / turns / jump / fall / land) is generated by the Moveset Free extension,
which measures this exact rig (limb lengths, shoulder and hip width) and retargets its motion onto it:
alternating legs with knee flex, planted feet, counter-swinging arms, pelvis sway, breathing idle.
Clips are baked in place (no root travel); the game scales playback by real speed so feet don't slide.

Sit (desk chair) and drive (car seat) are static poses authored here by aiming bones at targets,
so they are computed from the rig's real rest directions rather than guessed rotations.
"""
import importlib
import json
import math
import addon_utils
import bpy
from mathutils import Matrix, Vector

LOCO = [  # (action name in GLB, moveset mode). jog is a runtime blend of walk and run.
    ("idle", "idle"),
    ("walk", "walk"),
    ("run", "run"),
    ("sprint", "sprint"),
    ("turn_left", "turn_left"),
    ("turn_right", "turn_right"),
    ("jump", "jump_start"),
    ("fall", "fall_loop"),
    ("land", "land_soft"),
]


def _moveset():
    addon_utils.enable("bl_ext.blender_org.moveset", default_set=True)
    ms = importlib.import_module("bl_ext.blender_org.moveset")
    core = importlib.import_module("bl_ext.blender_org.moveset.core")
    rtm = importlib.import_module("bl_ext.blender_org.moveset.retarget")
    return ms, core, rtm


def bake_locomotion(arm, fps=30):
    ms, core, rtm = _moveset()
    scene = bpy.context.scene
    scene.render.fps, scene.render.fps_base = fps, 1.0
    lib = ms.library()
    ch = ms.new_char(arm)
    # relaxed human hands: fingers softly curled and together, thumb tucked, wrist neutral; calm idle
    for st in ch["states"].values():
        st["walk"].update(curl=0.6, spread=1.0, thumb=12, wflex=2, wdev=1, lag=0.3)
        st["idle"].update(fidget=0.06, look=8)
    for _, mode in LOCO:
        if mode not in ("walk", "idle"):
            a = lib["actions"][mode]
            ms.take_lib(ch, a["action"], a["params"])
    ch = core.fill_char(ms.ensure_manners(ch))
    ms.put_char(arm, ch)

    bpy.context.view_layer.objects.active = arm
    bpy.ops.object.mode_set(mode="POSE")
    rt = rtm.Retarget(arm)
    rt.root_motion = False
    info = {}
    for name, mode in LOCO:
        clip = core.sample_clip(ch, "normal", mode, ms.lookup_for(ch), fps)
        act = rt.bake(name, clip, fps, 0.0, None)
        speed = clip.get("speed")
        if speed is None and clip.get("motion"):
            speed = math.hypot(clip["motion"][0], clip["motion"][2])
        info[name] = {"loop": bool(clip["loop"]), "seconds": round(clip["length"], 4),
                      "speed": round(speed * rt.scale, 4) if speed else 0.0}
        act.use_fake_user = True
    rt.rest()
    bpy.ops.object.mode_set(mode="OBJECT")
    arm.animation_data.action = None
    return info


# ---------------------------------------------------------------- authored static poses
def _aim(arm, pb_name, direction, up_hint=None):
    """Rotate pose bone so its Y axis (bone direction) points along world `direction`, keeping twist minimal."""
    pb = arm.pose.bones[pb_name]
    bpy.context.view_layer.update()
    cur = (arm.matrix_world.to_3x3() @ pb.matrix.to_3x3()) @ Vector((0, 1, 0))
    rot = cur.normalized().rotation_difference(direction.normalized())
    mw = arm.matrix_world
    world = mw @ pb.matrix
    loc = world.to_translation()
    new = Matrix.Translation(loc) @ rot.to_matrix().to_4x4() @ Matrix.Translation(-loc) @ world
    pb.matrix = mw.inverted() @ new
    bpy.context.view_layer.update()


def _bend(arm, pb_name, axis_world, angle):
    pb = arm.pose.bones[pb_name]
    bpy.context.view_layer.update()
    mw = arm.matrix_world
    world = mw @ pb.matrix
    loc = world.to_translation()
    R = Matrix.Rotation(angle, 4, axis_world.normalized())
    pb.matrix = mw.inverted() @ (Matrix.Translation(loc) @ R @ Matrix.Translation(-loc) @ world)
    bpy.context.view_layer.update()


def _key_static(arm, name):
    act = bpy.data.actions.get(name)
    if act:
        bpy.data.actions.remove(act)
    act = bpy.data.actions.new(name)
    act.use_fake_user = True
    arm.animation_data_create()
    arm.animation_data.action = act
    for pb in arm.pose.bones:
        pb.rotation_mode = "QUATERNION"
        for f in (1, 2):
            pb.keyframe_insert("rotation_quaternion", frame=f)
            pb.keyframe_insert("location", frame=f)
    act.use_frame_range = True
    act.frame_start, act.frame_end = 1, 2
    arm.animation_data.action = None
    return act


def _reset(arm):
    for pb in arm.pose.bones:
        pb.rotation_mode = "QUATERNION"
        pb.matrix_basis = Matrix.Identity(4)
    bpy.context.view_layer.update()


def bake_seated(arm):
    """'sit' = desk chair, hands on keyboard; 'drive' = car seat, hands on wheel. Character faces -Y."""
    D = Vector((0, -1, 0))   # forward
    DN = Vector((0, 0, -1))
    out = {}
    for name, hip_lift, hand_fwd, hand_h, hand_w, lean in (
        ("sit", 0.0, 0.40, 0.0, 0.17, 0.10),
        ("drive", 0.0, 0.42, 0.20, 0.20, -0.22),
    ):
        bpy.ops.object.mode_set(mode="POSE")
        _reset(arm)
        mw = arm.matrix_world
        pbs = arm.pose.bones
        # torso lean (negative = reclined)
        _bend(arm, "spine_01", Vector((1, 0, 0)), -lean * 0.5)
        _bend(arm, "spine_02", Vector((1, 0, 0)), -lean * 0.5)
        # thighs forward and slightly apart, shins down, feet flat
        for s, sx in (("l", 1), ("r", -1)):
            _aim(arm, f"thigh_{s}", D + Vector((sx * 0.12, 0, -0.08 if name == "sit" else 0.12)))
            _aim(arm, f"calf_{s}", DN + D * (0.08 if name == "sit" else 0.75))
            _aim(arm, f"foot_{s}", D + DN * 0.35)
        bpy.context.view_layer.update()
        # arms: upper arm hangs down/forward, forearm reaches to keyboard/wheel
        chest = mw @ pbs["spine_03"].head
        for s, sx in (("l", 1), ("r", -1)):
            sh = mw @ pbs[f"upperarm_{s}"].head
            target = Vector((sx * hand_w, chest.y - hand_fwd, sh.z - 0.42 + hand_h))
            # two-bone solve in the plane containing shoulder, target and a downward/outward elbow hint
            L1 = pbs[f"upperarm_{s}"].length
            L2 = pbs[f"lowerarm_{s}"].length
            d = target - sh
            dist = min(d.length, (L1 + L2) * 0.999)
            a = math.acos(max(-1, min(1, (L1 * L1 + dist * dist - L2 * L2) / (2 * L1 * dist))))
            hint = Vector((sx * 0.6, 0.2, -1)).normalized()
            n = d.cross(hint).normalized()
            upper_dir = Matrix.Rotation(-a, 3, n) @ d.normalized()
            if upper_dir.z > (Matrix.Rotation(a, 3, n) @ d.normalized()).z:
                upper_dir = Matrix.Rotation(a, 3, n) @ d.normalized()
            _aim(arm, f"upperarm_{s}", upper_dir)
            elbow = mw @ pbs[f"lowerarm_{s}"].head
            _aim(arm, f"lowerarm_{s}", sh + d.normalized() * dist - elbow)
            _aim(arm, f"hand_{s}", D + DN * (0.35 if name == "sit" else -0.1))
        _bend(arm, "head", Vector((1, 0, 0)), -0.12 if name == "sit" else 0.05)
        _key_static(arm, name)
        bpy.ops.object.mode_set(mode="OBJECT")
        out[name] = {"loop": False, "seconds": 0.0, "speed": 0.0}
    _reset(arm)
    return out


def write_info(info, path):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(info, f, indent=1)
